
import streamlit as st
import pandas as pd
import joblib

# -----------------------------------
# 1. Load trained model and artifacts
# -----------------------------------
model = joblib.load("SVM_Heart.pkl")
scaler = joblib.load("scaler.pkl")
expected_columns = joblib.load("columns.pkl")

NUMERIC_COLUMNS = [
    "Age",
    "RestingBP",
    "Cholesterol",
    "MaxHR"
]

# -----------------------------------
# 2. Streamlit interface
# -----------------------------------
st.set_page_config(
    page_title="Heart Disease Prediction",
    page_icon="❤️",
    layout="centered"
)

st.title("❤️ Heart Disease Prediction")
st.markdown("Provide the following details.")

st.info(
    "This application is for educational purposes "
    "and is not a medical diagnosis."
)

# -----------------------------------
# 3. Collect user inputs
# -----------------------------------
age = st.slider("Age", 18, 100, 40)

sex = st.selectbox("Sex", ["M", "F"])

chest_pain = st.selectbox(
    "Chest Pain Type",
    ["ATA", "NAP", "TA", "ASY"]
)

resting_bp = st.number_input(
    "Resting Blood Pressure (mm Hg)",
    min_value=0,
    max_value=250,
    value=120
)

cholesterol = st.number_input(
    "Cholesterol (mg/dL)",
    min_value=0,
    max_value=700,
    value=200
)

fasting_bs = st.selectbox(
    "Fasting Blood Sugar > 120 mg/dL",
    [0, 1]
)

resting_ecg = st.selectbox(
    "Resting ECG",
    ["Normal", "ST", "LVH"]
)

max_hr = st.slider(
    "Maximum Heart Rate",
    60, 220, 150
)

exercise_angina = st.selectbox(
    "Exercise-Induced Angina",
    ["Y", "N"]
)

oldpeak = st.number_input(
    "Oldpeak (ST Depression)",
    min_value=-5.0,
    max_value=10.0,
    value=1.0,
    step=0.1
)

st_slope = st.selectbox(
    "ST Slope",
    ["Up", "Flat", "Down"]
)

# -----------------------------------
# 4. Prediction
# -----------------------------------
if st.button("Predict", type="primary"):

    # Match LabelEncoder's alphabetical mapping
    # Sex: F = 0, M = 1
    # ExerciseAngina: N = 0, Y = 1

    raw_input = {
        "Age": age,
        "Sex": 1 if sex == "M" else 0,
        "ChestPainType": chest_pain,
        "RestingBP": resting_bp,
        "Cholesterol": cholesterol,
        "FastingBS": fasting_bs,
        "RestingECG": resting_ecg,
        "MaxHR": max_hr,
        "ExerciseAngina": 1 if exercise_angina == "Y" else 0,
        "Oldpeak": oldpeak,
        "ST_Slope": st_slope
    }

    try:
        # Create a DataFrame from user input
        input_df = pd.DataFrame([raw_input])

        # Apply one-hot encoding to the same columns
        # used during model training
        input_df = pd.get_dummies(
            input_df,
            columns=[
                "ChestPainType",
                "RestingECG",
                "ST_Slope"
            ],
            dtype=int
        )

        # Match the exact features and order used by the SVM
        input_df = input_df.reindex(
            columns=expected_columns,
            fill_value=0
        )

        # Scale ONLY the four columns used to fit the scaler
        input_df[NUMERIC_COLUMNS] = scaler.transform(
            input_df[NUMERIC_COLUMNS]
        )

        # Predict using the trained SVM
        prediction = model.predict(input_df)[0]

        st.subheader("Prediction Result")

        if prediction == 1:
            st.error("The model predicts a positive heart disease class.")
        else:
            st.success("The model predicts a negative heart disease class.")

        # Display class probabilities if supported
        if hasattr(model, "predict_proba"):
            probabilities = model.predict_proba(input_df)[0]

            st.subheader("Model Class Probabilities")

            for label, probability in zip(
                model.classes_, probabilities
            ):
                st.write(
                    f"Class {label}: {probability:.2%}"
                )

        with st.expander("View processed input"):
            st.dataframe(input_df)

    except Exception as e:
        st.error(f"Prediction failed: {e}")
        st.write(
            "Check that the model, scaler, and saved columns "
            "were generated by the same training pipeline."
        )
